import { supabase } from '../../config/supabase';
import { Invoice, InvoiceDetail, InvoiceLineItem, InvoiceListItem } from '../../types';
import { InvoiceSchema } from '../../types/schemas';

// ─────────────────────────────────────────────────────────────────────────────
// Raw DB row shapes returned by joined queries
// ─────────────────────────────────────────────────────────────────────────────

type RawInvoiceRow = {
  id: string;
  invoice_number: string;
  order_id: string;
  customer_id: string;
  total_amount: number;
  status: string;
  pdf_url: string | null;
  pdf_generated_at: string | null;
  notes: string | null;
  issued_at: string;
  created_at: string;
  updated_at: string;
};

type RawOrderItemRow = {
  id: string;
  order_id: string;
  menu_item_id: string;
  quantity: number;
  unit_price: number;
  subtotal: number;
  menu_items?: { name: string };
};

type RawUserRow = {
  id: string;
  name: string;
  email: string;
};

// ─────────────────────────────────────────────────────────────────────────────
// WRITE
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Insert a new invoice row.
 * invoice_number is auto-generated by a PostgreSQL trigger — do NOT pass it here.
 */
export const insertInvoice = async (payload: {
  order_id: string;
  customer_id: string;
  total_amount: number;
}): Promise<Invoice> => {
  const { data, error } = await supabase
    .from('invoices')
    .insert(payload)
    .select('*')
    .single();

  if (error || !data) {
    throw new Error(`Failed to create invoice: ${error?.message ?? 'No data returned'}`);
  }

  return InvoiceSchema.parse(data);
};

/**
 * Save the Supabase Storage path for the generated PDF and stamp pdf_generated_at.
 */
export const updateInvoicePdfPath = async (
  invoiceId: string,
  pdfStoragePath: string
): Promise<Invoice> => {
  const { data, error } = await supabase
    .from('invoices')
    .update({
      pdf_url: pdfStoragePath,
      pdf_generated_at: new Date().toISOString(),
    })
    .eq('id', invoiceId)
    .select('*')
    .single();

  if (error || !data) {
    throw new Error(`Failed to update invoice PDF path: ${error?.message ?? 'No data returned'}`);
  }

  return InvoiceSchema.parse(data);
};

