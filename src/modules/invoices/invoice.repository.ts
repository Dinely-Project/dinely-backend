/** List all invoices for a specific customer, newest first. */
export const findInvoicesByCustomer = async (
  customerId: string,
  filters: { status?: string; limit: number; offset: number }
): Promise<InvoiceListItem[]> => {
  let query = supabase
    .from('invoices')
    .select('id, invoice_number, order_id, total_amount, status, issued_at')
    .eq('customer_id', customerId)
    .order('issued_at', { ascending: false })
    .range(filters.offset, filters.offset + filters.limit - 1);

  if (filters.status) {
    query = query.eq('status', filters.status);
  }

  const { data, error } = await query;

  if (error) {
    throw new Error(`Failed to fetch customer invoices: ${error.message}`);
  }

  return (data ?? []) as InvoiceListItem[];
};
