/** Fetch a plain invoice row by its primary key. */
export const findInvoiceById = async (id: string): Promise<Invoice | null> => {
  const { data, error } = await supabase
    .from('invoices')
    .select('*')
    .eq('id', id)
    .limit(1);

  if (error) {
    throw new Error(`Failed to fetch invoice: ${error.message}`);
  }

  if (!data || data.length === 0) return null;
  return InvoiceSchema.parse(data[0]);
};

/** Fetch a plain invoice row by the linked order_id (UNIQUE constraint, returns at most one). */
export const findInvoiceByOrderId = async (orderId: string): Promise<Invoice | null> => {
  const { data, error } = await supabase
    .from('invoices')
    .select('*')
    .eq('order_id', orderId)
    .limit(1);

  if (error) {
    throw new Error(`Failed to fetch invoice by order: ${error.message}`);
  }

  if (!data || data.length === 0) return null;
  return InvoiceSchema.parse(data[0]);
};

/**
 * Fetch full invoice detail for a given invoice id:
 * invoice row + customer info + order line items (with menu item names).
 */
export const findInvoiceDetail = async (id: string): Promise<InvoiceDetail | null> => {
  // 1. Fetch the invoice row
  const { data: invData, error: invError } = await supabase
    .from('invoices')
    .select('*')
    .eq('id', id)
    .limit(1);

  if (invError) {
    throw new Error(`Failed to fetch invoice detail: ${invError.message}`);
  }

  if (!invData || invData.length === 0) return null;

  const raw = invData[0] as RawInvoiceRow;
  const invoice = InvoiceSchema.parse(raw);

  // 2. Fetch customer info
  const { data: userData, error: userError } = await supabase
    .from('users')
    .select('id, name, email')
    .eq('id', invoice.customer_id)
    .limit(1);

  if (userError) {
    throw new Error(`Failed to fetch customer for invoice: ${userError.message}`);
  }

  const customer = ((userData ?? []) as RawUserRow[])[0];

  // 3. Fetch order items with menu item names (prices already snapshotted)
  const { data: itemsData, error: itemsError } = await supabase
    .from('order_items')
    .select('*, menu_items(name)')
    .eq('order_id', invoice.order_id);

  if (itemsError) {
    throw new Error(`Failed to fetch order items for invoice: ${itemsError.message}`);
  }

  const items: InvoiceLineItem[] = ((itemsData ?? []) as RawOrderItemRow[]).map((row) => ({
    name: row.menu_items?.name ?? 'Unknown item',
    quantity: row.quantity,
    unit_price: row.unit_price,
    subtotal: row.subtotal,
  }));

  return {
    ...invoice,
    customer_name: customer?.name ?? 'Unknown',
    customer_email: customer?.email ?? '',
    items,
  };
};

